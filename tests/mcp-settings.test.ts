 expect(parseMcpImport('{"servers":{"docs":{"type":"http","url":"https://example.com/mcp"}}}')[0].server.name).toBe('docs');
 expect(parseMcpImport('{"name":"Local","command":"python3","args":["server.py"]}')[0].server).toMatchObject({name:'Local',transport:'stdio',command:'python3',args:['server.py']});
 expect(parseMcpImport('{"url":"https://example.com/mcp"}')[0].server.name).toBe('example.com');
 for(const invalid of ['null','[]','{"mcpServers":[]}','{"mcpServers":{}}','{"url":"javascript:alert(1)"}','{"command":"npx","args":[1]}','{"type":"sse","url":"https://example.com/sse"}','{"url":"https://example.com","headers":{"Token":5}}','{"url":"${input:server}"}'])expect(()=>parseMcpImport(invalid)).toThrow();
