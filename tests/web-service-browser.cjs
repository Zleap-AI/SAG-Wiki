const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_BROWSER_CHANNEL||'chrome',headless:true,args:['--no-proxy-server']});
 try {
  const context=await browser.newContext({locale:'zh-CN',viewport:{width:1280,height:900}}),page=await context.newPage();
  page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.SAG_WEB_URL);
  if(new URL(process.env.SAG_WEB_URL).hostname!=='127.0.0.1')assert.equal(await page.evaluate(()=>isSecureContext),false);
  await page.locator('#web-code').fill('invalid');await page.getByRole('button',{name:'进入知识库'}).click();
  await page.getByRole('alert').filter({hasText:'访问码不正确'}).waitFor();
  await page.locator('#web-code').fill(process.env.SAG_WEB_CODE);
  await page.getByRole('button',{name:'进入知识库'}).click();
  await page.locator('.library-files h1').filter({hasText:'项目资料'}).waitFor();
  for(const entry of [page.locator('.tree').getByRole('button',{name:'项目资料',exact:true}),page.getByRole('button',{name:'发布流程.md',exact:true})]){
   await entry.click({button:'right'});
   await page.getByRole('menu').waitFor();
   assert.equal(await page.getByRole('menuitem',{name:/^(移除|从知识库移除)$/}).count(),0,'web menus must not remove shared knowledge-base entries');
   await page.keyboard.press('Escape');
  }
  await page.getByRole('button',{name:'发布流程.md',exact:true}).click();
  await page.locator('#rich-editor').getByText('Vega release checklist VX-417').waitFor();
  const editor=page.locator('#rich-editor [contenteditable=true], #rich-editor[contenteditable=true]').first();
  await editor.press('End');await editor.press('Enter');await editor.pressSequentially('Browser edit marker');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByText('已保存',{exact:true}).waitFor();
  await page.locator('.workspace-switch').getByText('搜索',{exact:true}).click();
  await page.locator('.search-entry input').fill('release');
  await page.locator('.search-entry input').press('Enter');
  await page.locator('.search-result').first().waitFor();
  await page.locator('.workspace-switch').getByText('问答',{exact:true}).click();
  const input=page.locator('.composer textarea, .composer input').first();
  await input.fill('What is the release checklist number?');
  await input.press('Enter');
  await page.getByText('The checklist is VX-417.',{exact:false}).first().waitFor();
  await page.locator('.workspace-switch').getByText('文件',{exact:true}).click();
  if(!await page.locator('.library-files h1').filter({hasText:'项目资料'}).count())await page.locator('.tree').getByRole('button',{name:'项目资料',exact:true}).click();
  await page.getByRole('button',{name:'发布流程.md',exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  await page.close();
  const reopened=await context.newPage();
  await reopened.goto(process.env.SAG_WEB_URL);
  await reopened.getByRole('button',{name:'退出网页'}).waitFor();
  await reopened.getByRole('button',{name:'退出网页'}).click();
  await reopened.reload();
  await reopened.locator('#web-code').waitFor();
  await reopened.locator('#web-code').fill(process.env.SAG_WEB_CODE);
  await reopened.getByRole('button',{name:'进入知识库'}).click();
  await reopened.getByRole('button',{name:'退出网页'}).waitFor();
  const rotation=await fetch(process.env.SAG_WEB_TEST_ROTATE,{method:'POST'});
  assert(rotation.ok,'fixture should rotate the code');
  const newCode=await rotation.text();
  await reopened.locator('#web-code').waitFor();
  assert.equal(await reopened.evaluate(()=>localStorage.getItem('sag.web.code')),null);
  await reopened.locator('#web-code').fill(process.env.SAG_WEB_CODE);
  await reopened.getByRole('button',{name:'进入知识库'}).click();
  await reopened.getByRole('alert').filter({hasText:'访问码不正确'}).waitFor();
  await reopened.locator('#web-code').fill(newCode);
  await reopened.getByRole('button',{name:'进入知识库'}).click();
  await reopened.getByRole('button',{name:'退出网页'}).waitFor();
  const mobile=await browser.newContext({locale:'zh-CN',viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const phone=await mobile.newPage();await phone.goto(process.env.SAG_WEB_URL);
  await phone.locator('#web-code').fill(newCode);
  await phone.getByRole('button',{name:'进入知识库'}).tap({timeout:5000});
  await phone.getByRole('button',{name:'发布流程.md',exact:true}).click();
  await phone.locator('#rich-editor').getByText('Vega release checklist VX-417').waitFor();
  assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.close();
  console.log('Browser: sign-in, remembered access, code rotation, sign-out, files, search and Q&A passed');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
