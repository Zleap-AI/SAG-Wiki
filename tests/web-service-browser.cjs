  await sidebar.waitFor();
  assert.equal(await contentWidth(),fullWidth);
  await phone.tap('.mobile-sidebar-backdrop',{position:{x:fullWidth-20,y:100}});
  await sidebar.waitFor({state:'hidden'});
  await openSidebar.tap();
  await sidebar.getByRole('button',{name:'收起侧边栏'}).tap();
  await sidebar.waitFor({state:'hidden'});
  await phone.getByRole('button',{name:'发布流程.md',exact:true}).click();
  await phone.locator('#rich-editor').getByText('Vega release checklist VX-417').waitFor();
  assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const tabs=phone.locator('.workspace-switch');
  const expectDetail=async()=>{
   await tabs.waitFor({state:'hidden'});
   await openSidebar.waitFor({state:'hidden'});
   assert.equal(await contentWidth(),fullWidth);
  };
  await expectDetail();
  await phone.locator('.editor-head').getByTitle('返回文件夹').tap();
  await phone.getByRole('button',{name:'发布流程.md',exact:true}).waitFor();
