  const openSidebar=phone.getByRole('button',{name:'展开侧边栏'});
  const contentWidth=()=>phone.locator('main.workspace').evaluate(el=>el.getBoundingClientRect().width);
  await openSidebar.waitFor();
  assert.equal(await sidebar.isVisible(),false);
  const fullWidth=await phone.evaluate(()=>document.documentElement.clientWidth);
  assert.equal(await contentWidth(),fullWidth);
